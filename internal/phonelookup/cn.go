package phonelookup

func matchService(candidates ...string) (svc serviceNumber, ok bool) {
	best := 0
	for _, cand := range candidates {
		if cand == "" {
			continue
		}
		if item, found := cnServiceNumbers[cand]; found && len(cand) >= best {
			svc, ok, best = item, true, len(cand)
		}
	}
	return svc, ok
}

func matchCNMobile(national string) (string, bool) {
	if len(national) < 3 || national[0] != '1' {
		return "", false
	}
	return matchLongest(national, cnMobilePrefixes)
}

func matchCNArea(national string) (string, bool) {
	n := national
	if len(n) > 0 && n[0] != '0' {
		n = "0" + n
	}
	if len(n) < 3 {
		return "", false
	}
	return matchLongest(n, cnAreaCodes)
}

